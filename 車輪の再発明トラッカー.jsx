// BFS と A* の探索比較用データ（固定迷路で探索順を事前計算）
const PF = (() => {
  const W = 13;
  const H = 9;
  const walls = new Set();
  for (let y = 0; y <= 5; y++) walls.add(`6,${y}`); // 中央の壁（下に隙間）
  const start = [0, 4];
  const goal = [12, 4];
  const keyOf = (x, y) => `${x},${y}`;
  function run(useHeuristic) {
    const open = [{ x: start[0], y: start[1], g: 0 }];
    const prev = {};
    const seen = new Set([keyOf(start[0], start[1])]);
    const order = [];
    while (open.length) {
      let bi = 0;
      if (useHeuristic) {
        let best = Infinity;
        open.forEach((n, i) => {
          const f = n.g + Math.abs(goal[0] - n.x) + Math.abs(goal[1] - n.y);
          if (f < best) {
            best = f;
            bi = i;
          }
        });
      }
      const cur = open.splice(bi, 1)[0];
      order.push(keyOf(cur.x, cur.y));
      if (cur.x === goal[0] && cur.y === goal[1]) break;
      for (const [dx, dy] of [[1, 0], [0, 1], [-1, 0], [0, -1]]) {
        const nx = cur.x + dx;
        const ny = cur.y + dy;
        const k = keyOf(nx, ny);
        if (nx < 0 || ny < 0 || nx >= W || ny >= H || walls.has(k) || seen.has(k)) continue;
        seen.add(k);
        prev[k] = keyOf(cur.x, cur.y);
        open.push({ x: nx, y: ny, g: cur.g + 1 });
      }
    }
    const idx = {};
    order.forEach((k, i) => (idx[k] = i));
    const path = new Set();
    let k = keyOf(goal[0], goal[1]);
    while (k) {
      path.add(k);
      k = prev[k];
    }
    return { order, idx, path };
  }
  return { W, H, walls, start, goal, bfs: run(false), astar: run(true) };
})();

