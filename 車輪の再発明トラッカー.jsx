const HASH_KEYS = ["cat", "dog", "fox", "bee", "owl", "ant", "elk", "koi"];
function DemoHash() {
  const [count, setCount] = useState(0);
  const [calc, setCalc] = useState("");
  const buckets = Array.from({ length: 5 }, () => []);
  HASH_KEYS.slice(0, count).forEach((key) => {
    const code = [...key].reduce((s, ch) => s + ch.charCodeAt(0), 0);
    buckets[code % 5].push({ key, code });
  });
  const add = () => {
    if (count >= HASH_KEYS.length) return;
    const key = HASH_KEYS[count];
    const code = [...key].reduce((s, ch) => s + ch.charCodeAt(0), 0);
    setCalc(`"${key}" → 文字コード合計 ${code} → ${code} % 5 = バケツ ${code % 5}`);
    setCount((c) => c + 1);
  };
  return (
    <div className="demo">
      <div className="demo-controls">
        <button className="demo-btn" onClick={add}>＋ キーを追加</button>
        <button className="demo-btn" onClick={() => { setCount(0); setCalc(""); }}>リセット</button>
      </div>
      <div className="hash-buckets">
        {buckets.map((items, i) => (
          <div key={i} className="hash-b">
            <h4>バケツ {i}</h4>
            {items.map((item) => (
              <div key={item.key} className="hash-chip">{item.key}</div>
            ))}
          </div>
        ))}
      </div>
      {calc && <p className="hash-calc">{calc}</p>}
      <p className="demo-cap">
        キーを数値化（ハッシュ）して割った余りで置き場所を決めるので、探すときも同じ計算で一発で場所がわかります。同じバケツに複数入る（衝突する）ことがあり、縦に鎖のように連なるのがチェイン法です。
      </p>
    </div>
  );
}

