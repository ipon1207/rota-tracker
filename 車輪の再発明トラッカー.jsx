const FF_W = 16;
const FF_H = 10;
const FF = (() => {
  const walls = new Set();
  for (let x = 0; x < FF_W; x++) { walls.add(`${x},0`); walls.add(`${x},${FF_H - 1}`); }
  for (let y = 0; y < FF_H; y++) { walls.add(`0,${y}`); walls.add(`${FF_W - 1},${y}`); }
  for (let y = 3; y <= 8; y++) walls.add(`6,${y}`);
  for (let x = 6; x <= 11; x++) walls.add(`${x},3`);
  for (let y = 5; y <= 6; y++) walls.add(`11,${y}`);
  // 塗り順をBFSで事前計算（seedから壁を避けて広がる）
  const order = [];
  const seen = new Set(["2,2"]);
  const q = [[2, 2]];
  while (q.length) {
    const [x, y] = q.shift();
    order.push(`${x},${y}`);
    for (const [dx, dy] of [[1, 0], [0, 1], [-1, 0], [0, -1]]) {
      const k = `${x + dx},${y + dy}`;
      if (walls.has(k) || seen.has(k)) continue;
      const nx = x + dx, ny = y + dy;
      if (nx < 0 || ny < 0 || nx >= FF_W || ny >= FF_H) continue;
      seen.add(k);
      q.push([nx, ny]);
    }
  }
  const idx = {};
  order.forEach((k, i) => (idx[k] = i));
  return { walls, order, idx };
})();

