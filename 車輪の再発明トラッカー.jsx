// キーワード文字列を括弧の外の「、」で分割してチップ化する
function splitKeywords(kw) {
  const out = [];
  let cur = "";
  let depth = 0;
  for (const ch of kw) {
    if (ch === "（" || ch === "(") depth++;
    if (ch === "）" || ch === ")") depth = Math.max(0, depth - 1);
    if (ch === "、" && depth === 0) {
      if (cur.trim()) out.push(cur.trim());
      cur = "";
    } else {
      cur += ch;
    }
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

